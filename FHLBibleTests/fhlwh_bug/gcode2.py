import re
from typing import List


def replace_all_literal(text: str, search: str, replacement: str) -> str:
    return text.replace(search, replacement)


def replace_by_table(text: str, from_list: List[str], to_list: List[str]) -> str:
    out = text
    for i in range(len(from_list)):
        out = replace_all_literal(out, from_list[i], to_list[i])
    return out

